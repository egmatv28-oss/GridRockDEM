@ti.func
def sigvi_field():
    """Занятость клеток + вертикальная перегрузка (gOcc/sigVI), столбик сверху-вниз.

    Выделена из refresh_field, чтобы вызывать КАЖДЫЙ подшаг из слитого ядра
    phys_substep (solver.py): sigVI читают боковой распор (forces_reset),
    конфайнмент трещин (forces_contact) и трение о пол/стены (forces_integrate) —
    раньше поле обновлялось раз в TOPO_EVERY подшагов и успевало устареть."""
    for c in range(N):
        gOcc[c] = 0
        sigVI[c] = 0.0
    for i in range(bcount[None]):
        cxi = clamp_cell(bx[i])
        cyi = row_cell(by[i])
        gOcc[cyi * COLS + cxi] = 1
    for x in range(COLS):
        # loadCur — уже Н (вес породы над колонкой шириной 1 клетку)
        carry = loadCur[None]
        started = 0
        y = 0
        while y < ROWS:
            c = y * COLS + x
            if gOcc[c] == 1:
                sigVI[c] = carry
                carry += BMASS_UNIT * P[None].g
                started = 1
            else:
                # РАЗРЫВ сплошности: вес через пустоту не передаётся (сводовая
                # разгрузка). Иначе вся вышележащая порода (loadCur + вес колонны)
                # "давила" на уединённый обломок в дыре: боковой распор, преднатяг
                # и трение о стенки выходили на 2 порядка больше веса блока -
                # блоки ОТЛЕТАЛИ при спавне и ПРИЛИПАЛИ к границам/боковым граням.
                #
                # Пустая клетка ДО первого блока колонки — это не полость, а
                # просевшая поверхность/сдвиг верхнего блока в соседнюю клетку.
                # Верхняя нагрузка ovf приложена к САМОМУ ВЕРХНЕМУ блоку колонки
                # (find_top_blocks), поэтому carry здесь сбрасывать нельзя: иначе
                # вся колонка теряла loadCur (оставался только её собственный вес),
                # sideF на этой грани падал на ~98%, и возникала нефизичная
                # асимметричная разгрузка/удар (свод "уезжал" в эллипс и
                # запускалась глобальная лавина). Сброс — только ПОСЛЕ первого
                # занятого блока, т.е. на настоящей полости внутри массива.
                if started == 1:
                    carry = 0.0
            y += 1


@ti.func
def bond_stress_field():
    """Прокси главных СЖАТИЙ по блокам (bSxx/bSyy) из сил связей и швов.

    Для каждой целой связи и шва (BOND_JOINT) осевое сжатие раскладывается по осям
    (× ux²/× uy²) и суммируется на концевые блоки. Швы включены, чтобы разрыв
    полосы связей не обнулял прокси σ_xx — легенда и пуассоново раскалывание
    видят сохранённое боковое сжатие. Направление с большим сжатием — локальное
    главное сжатие σ_c: по нему считается пуассоново раскалывание в forces_bonds
    (трещины ВДОЛЬ σ_c — вертикальные в поле, вдоль контура у выработки)."""
    for i in range(bcount[None]):
        bSxx[i] = 0.0
        bSyy[i] = 0.0
    for bd in range(bondCount[None]):
        if bondIntact[bd] != BOND_DEAD:
            a = bondA[bd]
            b = bondB[bd]
            dx = bx[b] - bx[a]
            dy = by[b] - by[a]
            d = ti.sqrt(dx * dx + dy * dy)
            if d > 1e-9 and brest[bd] > 1e-9:
                w = bsz[a]
                if bsz[b] < w:
                    w = bsz[b]
                tension = P[None].E * w / brest[bd] * (d - brest[bd])
                if tension < 0.0:
                    c = -tension
                    ux = dx / d
                    uy = dy / d
                    ti.atomic_add(bSxx[a], c * ux * ux)
                    ti.atomic_add(bSxx[b], c * ux * ux)
                    ti.atomic_add(bSyy[a], c * uy * uy)
                    ti.atomic_add(bSyy[b], c * uy * uy)
    # Боковое обжатие граничных блоков задаётся ПРЯМОЙ силой sideF (вне домена
    # породы нет, «недостающая» наружу связь заменена этой силой). bSxx — СУММА
    # усилий связей, поэтому у краевого блока (1 горизонт. связь) она вдвое ниже,
    # чем у внутреннего (2 связи), хотя σ_xx там то же: возникал ЛОЖНЫЙ девиатор
    # |σ_yy−σ_xx| у границы, пуассоново раскалывание (split) рвало связи на кромке
    # модели, и оттуда шла лавина. Добавляем в bSxx вклад sideF — он и есть усилие
    # «недостающего» наружного соседа; профиль σ_xx по x становится ровным.
    for i in range(bcount[None]):
        if sideF[i] != 0.0:
            bSxx[i] += ti.abs(sideF[i])


@ti.kernel
def refresh_field():
    """Пересчитать топологию и поля напряжений.

    1) Занятость клеток блоком — по текущим позициям (без геометрии полости).
    2) Вертикальная перегрузка в каждой занятой клетке: нагрузка от поверхности
       + вес всего столба блоков НАД ней (сверху вниз).
    3) Горизонтальное удержание двумя встречными проходами (сверху вниз):
       блок держится слева/справа с давлением σ_h = K0·σ_v, ЕСЛИ сосед есть;
       у свободной грани (выработка) с этой стороны удержания нет.
    Пункты 1-2 вынесены в sigvi_field() — он зовётся каждый подшаг из
    phys_substep (свежий sigVI для распора/конфайнмента/трения)."""
    for c in range(N):
        holdL[c] = 0.0
        holdR[c] = 0.0
    sigvi_field()
    bond_stress_field()
    for y in range(ROWS):
        # слева-направо: удержание справа (σ_h от правого соседа)
        for x in range(COLS):
            c = y * COLS + x
            if gOcc[c] == 1 and x + 1 < COLS and gOcc[y * COLS + x + 1] == 1:
                holdR[c] = sigVI[c] * P[None].k0
        # справа-налево: удержание слева (σ_h от левого соседа)
        for j in range(COLS):
            x = COLS - 1 - j
            c = y * COLS + x
            if gOcc[c] == 1 and x - 1 >= 0 and gOcc[y * COLS + x - 1] == 1:
                holdL[c] = sigVI[c] * P[None].k0


